-- Migration إضافية وغير مدمّرة: لا تحذف أي جدول أو سجل طلبات.
-- نفّذ الملف مرة واحدة من Supabase SQL Editor قبل نشر ملفات التطبيق الجديدة.

begin;

create extension if not exists pgcrypto;
create extension if not exists pg_trgm;

alter table public.users
  add column if not exists instagram_company_id text;

-- توسيع قيد الدور الحالي (إن وجد) من دون تعديل بيانات المستخدمين.
do $$
declare
  constraint_row record;
  has_viewer_constraint boolean := false;
begin
  for constraint_row in
    select conname, pg_get_constraintdef(oid) as definition
    from pg_constraint
    where conrelid = 'public.users'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%role%'
  loop
    if constraint_row.definition ilike '%instagram_viewer%' then
      has_viewer_constraint := true;
    elsif constraint_row.definition ilike '%admin%'
      and constraint_row.definition ilike '%driver%'
      and constraint_row.definition ilike '%company%' then
      execute format('alter table public.users drop constraint %I', constraint_row.conname);
    end if;
  end loop;

  if not has_viewer_constraint and not exists (
    select 1 from pg_constraint
    where conrelid = 'public.users'::regclass
      and conname = 'users_role_wolforder_check'
  ) then
    alter table public.users
      add constraint users_role_wolforder_check
      check (role in ('admin', 'driver', 'company', 'instagram_viewer')) not valid;
    alter table public.users validate constraint users_role_wolforder_check;
  end if;
end
$$;

