create or replace function public.validate_instagram_viewer_company()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.role = 'instagram_viewer' then
    if new.instagram_company_id is null or not exists (
      select 1 from public.users company
      where company.id::text = new.instagram_company_id
        and company.role = 'company'
    ) then
      raise exception 'INVALID_INSTAGRAM_VIEWER_COMPANY' using errcode = 'P0001';
    end if;
  elsif new.instagram_company_id is not null then
    new.instagram_company_id := null;
  end if;
  return new;
end;
$$;

drop trigger if exists users_validate_instagram_viewer on public.users;
create trigger users_validate_instagram_viewer
before insert or update of role, instagram_company_id on public.users
for each row execute function public.validate_instagram_viewer_company();

create or replace function public.create_instagram_product(
  p_company_id text,
  p_name text,
  p_is_active boolean,
  p_variants jsonb,
  p_actor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_product public.instagram_products%rowtype;
  new_inventory public.instagram_inventory%rowtype;
  variant jsonb;
  variant_count integer;
  quantity_value integer;
begin
  if not exists (select 1 from public.users where id::text = p_company_id and role = 'company') then
    raise exception 'INVALID_COMPANY' using errcode = 'P0001';
  end if;
  if char_length(btrim(coalesce(p_name, ''))) not between 2 and 120 then
    raise exception 'INVALID_PRODUCT' using errcode = 'P0001';
  end if;
  if p_variants is null or jsonb_typeof(p_variants) <> 'array' then
    raise exception 'INVALID_VARIANTS' using errcode = 'P0001';
  end if;
  variant_count := jsonb_array_length(p_variants);
  if variant_count < 1 or variant_count > 200 then
    raise exception 'INVALID_VARIANTS' using errcode = 'P0001';
  end if;

  insert into public.instagram_products (company_id, name, is_active)
  values (p_company_id, btrim(p_name), coalesce(p_is_active, true))
  returning * into new_product;

  for variant in select value from jsonb_array_elements(p_variants)
  loop
    quantity_value := (variant->>'quantity')::integer;
    if char_length(btrim(coalesce(variant->>'color', ''))) < 1
      or char_length(btrim(coalesce(variant->>'size', ''))) < 1
      or quantity_value < 0 then
      raise exception 'INVALID_VARIANT' using errcode = 'P0001';
    end if;

    insert into public.instagram_inventory (
      product_id, color, size, initial_quantity, available_quantity, reserved_quantity, sold_quantity
    ) values (
      new_product.id, btrim(variant->>'color'), btrim(variant->>'size'),
      quantity_value, quantity_value, 0, 0
    ) returning * into new_inventory;

    insert into public.instagram_inventory_movements (
      inventory_id, movement_type, available_delta, reason, actor_id
    ) values (
      new_inventory.id, 'initial_stock', quantity_value, 'إنشاء المخزون الأساسي', p_actor_id
    );
  end loop;

  return to_jsonb(new_product);
end;
$$;

create or replace function public.add_instagram_variant(
  p_product_id uuid,
  p_color text,
  p_size text,
  p_quantity integer,
