create or replace function public.adjust_instagram_inventory(
  p_inventory_id uuid,
  p_delta integer,
  p_reason text,
  p_actor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  inventory_row public.instagram_inventory%rowtype;
begin
  if p_delta = 0 or char_length(btrim(coalesce(p_reason, ''))) < 3 then
    raise exception 'INVALID_ADJUSTMENT' using errcode = 'P0001';
  end if;
  select * into inventory_row from public.instagram_inventory where id = p_inventory_id for update;
  if not found then raise exception 'INVALID_INVENTORY' using errcode = 'P0001'; end if;
  if inventory_row.available_quantity + p_delta < 0 or inventory_row.initial_quantity + p_delta < 0 then
    raise exception 'INSUFFICIENT_AVAILABLE_STOCK' using errcode = 'P0001';
  end if;

  update public.instagram_inventory
  set initial_quantity = initial_quantity + p_delta,
      available_quantity = available_quantity + p_delta
  where id = p_inventory_id
  returning * into inventory_row;

  insert into public.instagram_inventory_movements (
    inventory_id, movement_type, available_delta, reason, actor_id
  ) values (
    p_inventory_id,
    case when p_delta > 0 then 'adjustment_in' else 'adjustment_out' end,
    p_delta, btrim(p_reason), p_actor_id
  );
  return to_jsonb(inventory_row);
end;
$$;

create or replace function public.create_instagram_order(
  p_public_slug text,
  p_customer_name text,
  p_customer_phone text,
  p_address text,
  p_order_type text,
  p_note text,
  p_items jsonb,
  p_idempotency_key uuid,
  p_request_fingerprint text,
  p_rate_bucket text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  company_value text;
  company_name_value text;
  order_row public.instagram_orders%rowtype;
  existing_order public.instagram_orders%rowtype;
  inventory_row record;
  item jsonb;
  item_quantity integer;
  item_inventory_id uuid;
  rate_count integer;
begin
  insert into public.instagram_public_rate_limits (bucket_key, window_started_at, request_count, updated_at)
  values (p_rate_bucket, now(), 1, now())
  on conflict (bucket_key) do update
  set request_count = case
        when instagram_public_rate_limits.window_started_at < now() - interval '10 minutes' then 1
        else instagram_public_rate_limits.request_count + 1
      end,
      window_started_at = case
        when instagram_public_rate_limits.window_started_at < now() - interval '10 minutes' then now()
        else instagram_public_rate_limits.window_started_at
      end,
      updated_at = now()
  returning request_count into rate_count;
  if rate_count > 30 then raise exception 'RATE_LIMITED' using errcode = 'P0001'; end if;

  select company_id into company_value
  from public.instagram_company_links
  where public_slug = p_public_slug and is_active = true;
  if company_value is null then raise exception 'INVALID_PUBLIC_LINK' using errcode = 'P0001'; end if;

  select name into company_name_value from public.users
  where id::text = company_value and role = 'company';
  if company_name_value is null then raise exception 'INVALID_COMPANY' using errcode = 'P0001'; end if;

  if p_order_type not in ('توصيل', 'شحن')
    or p_items is null
    or jsonb_typeof(p_items) <> 'array'
    or coalesce(jsonb_array_length(p_items), 0) not between 1 and 20 then
    raise exception 'INVALID_ORDER' using errcode = 'P0001';
  end if;

  select * into existing_order from public.instagram_orders where idempotency_key = p_idempotency_key;
  if found then
    return jsonb_build_object('id', existing_order.id, 'order_number', existing_order.order_number, 'duplicate', true);
  end if;

  perform pg_advisory_xact_lock(hashtextextended(company_value || ':' || p_request_fingerprint, 0));
  select * into existing_order
  from public.instagram_orders
  where company_id = company_value
    and request_fingerprint = p_request_fingerprint
    and created_at >= now() - interval '2 minutes'
  order by created_at desc
  limit 1;
  if found then
    return jsonb_build_object('id', existing_order.id, 'order_number', existing_order.order_number, 'duplicate', true);
  end if;

  insert into public.instagram_orders (
    company_id, company_name, customer_name, customer_phone, address, order_type,
    status, note, idempotency_key, request_fingerprint, request_ip_hash
  ) values (
    company_value, company_name_value, btrim(p_customer_name), p_customer_phone, btrim(p_address),
    p_order_type, 'قيد المتابعة', btrim(coalesce(p_note, '')), p_idempotency_key,
    p_request_fingerprint, p_rate_bucket
  ) returning * into order_row;

  -- ترتيب الأقفال يمنع deadlocks إذا وصلت طلبات متزامنة بترتيب أصناف مختلف.
  for item in
    select value from jsonb_array_elements(p_items)
    order by value->>'inventory_id'
  loop
    item_inventory_id := (item->>'inventory_id')::uuid;
    item_quantity := (item->>'quantity')::integer;
    if item_quantity not between 1 and 100 then raise exception 'INVALID_QUANTITY' using errcode = 'P0001'; end if;

    select i.id, i.product_id, i.color, i.size, i.available_quantity,
           p.name as product_name
    into inventory_row
    from public.instagram_inventory i
    join public.instagram_products p on p.id = i.product_id
    where i.id = item_inventory_id
      and i.is_active = true
      and p.is_active = true
      and p.company_id = company_value
    for update of i;

    if not found then raise exception 'INVALID_INVENTORY' using errcode = 'P0001'; end if;
    if inventory_row.available_quantity < item_quantity then
      raise exception 'OUT_OF_STOCK:%:%:%', inventory_row.product_name, inventory_row.color, inventory_row.size using errcode = 'P0001';
    end if;

    update public.instagram_inventory
    set available_quantity = available_quantity - item_quantity,
        reserved_quantity = reserved_quantity + item_quantity
    where id = item_inventory_id;

    insert into public.instagram_order_items (
      order_id, product_id, inventory_id, product_name, color, size, quantity
    ) values (
      order_row.id, inventory_row.product_id, item_inventory_id, inventory_row.product_name,
      inventory_row.color, inventory_row.size, item_quantity
    );

    insert into public.instagram_inventory_movements (
      inventory_id, order_id, movement_type, available_delta, reserved_delta, reason
    ) values (
      item_inventory_id, order_row.id, 'reservation', -item_quantity, item_quantity, 'حجز طلب إنستغرام'
    );
  end loop;

  insert into public.instagram_order_status_history (order_id, old_status, new_status)
  values (order_row.id, null, 'قيد المتابعة');

  return jsonb_build_object('id', order_row.id, 'order_number', order_row.order_number, 'duplicate', false);
end;
$$;

create or replace function public.update_instagram_order_state(
  p_order_id uuid,
  p_new_status text,
  p_actor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  order_row public.instagram_orders%rowtype;
  item_row record;
  previous_status text;
  old_bucket text;
  new_bucket text;
  available_change integer;
  reserved_change integer;
  sold_change integer;
begin
  if p_new_status not in ('قيد المتابعة', 'تم', 'مؤجل', 'ملغي', 'مرتجع') then
    raise exception 'INVALID_STATUS' using errcode = 'P0001';
  end if;
  select * into order_row from public.instagram_orders where id = p_order_id for update;
  if not found then raise exception 'INVALID_ORDER' using errcode = 'P0001'; end if;
  if order_row.status = p_new_status then return to_jsonb(order_row); end if;
  previous_status := order_row.status;

  old_bucket := case when previous_status in ('قيد المتابعة', 'مؤجل') then 'reserved' when previous_status = 'تم' then 'sold' else 'released' end;
  new_bucket := case when p_new_status in ('قيد المتابعة', 'مؤجل') then 'reserved' when p_new_status = 'تم' then 'sold' else 'released' end;

  if old_bucket <> new_bucket then
    for item_row in select inventory_id, quantity from public.instagram_order_items where order_id = p_order_id order by inventory_id
    loop
      perform 1 from public.instagram_inventory where id = item_row.inventory_id for update;
      available_change := 0; reserved_change := 0; sold_change := 0;
      if old_bucket = 'reserved' and new_bucket = 'sold' then reserved_change := -item_row.quantity; sold_change := item_row.quantity;
      elsif old_bucket = 'reserved' and new_bucket = 'released' then reserved_change := -item_row.quantity; available_change := item_row.quantity;
      elsif old_bucket = 'sold' and new_bucket = 'released' then sold_change := -item_row.quantity; available_change := item_row.quantity;
      elsif old_bucket = 'sold' and new_bucket = 'reserved' then sold_change := -item_row.quantity; reserved_change := item_row.quantity;
      elsif old_bucket = 'released' and new_bucket = 'reserved' then available_change := -item_row.quantity; reserved_change := item_row.quantity;
      elsif old_bucket = 'released' and new_bucket = 'sold' then available_change := -item_row.quantity; sold_change := item_row.quantity;
      end if;

      update public.instagram_inventory
      set available_quantity = available_quantity + available_change,
          reserved_quantity = reserved_quantity + reserved_change,
          sold_quantity = sold_quantity + sold_change
      where id = item_row.inventory_id
        and available_quantity + available_change >= 0
        and reserved_quantity + reserved_change >= 0
        and sold_quantity + sold_change >= 0;
      if not found then raise exception 'OUT_OF_STOCK' using errcode = 'P0001'; end if;

      insert into public.instagram_inventory_movements (
        inventory_id, order_id, movement_type, available_delta, reserved_delta, sold_delta, reason, actor_id
      ) values (
        item_row.inventory_id, p_order_id,
        case when new_bucket = 'released' and p_new_status = 'مرتجع' then 'return_release'
             when new_bucket = 'released' then 'cancellation_release'
             when new_bucket = 'sold' then 'sale'
             when old_bucket = 'released' then 'reopen_reservation'
             else 'status_rebalance' end,
        available_change, reserved_change, sold_change, previous_status || ' ← ' || p_new_status, p_actor_id
      );
    end loop;
  end if;

  update public.instagram_orders
  set status = p_new_status, status_changed_at = now(), updated_at = now()
  where id = p_order_id returning * into order_row;
  insert into public.instagram_order_status_history (order_id, old_status, new_status, actor_id)
  values (p_order_id, previous_status, p_new_status, p_actor_id);
  return to_jsonb(order_row);
end;
$$;

create or replace function public.assign_instagram_order_driver(
  p_order_id uuid,
  p_driver_id text,
  p_driver_name text,
  p_actor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare order_row public.instagram_orders%rowtype;
begin
  update public.instagram_orders
  set driver_id = p_driver_id, driver_name = btrim(p_driver_name), updated_at = now()
  where id = p_order_id and order_type = 'توصيل'
  returning * into order_row;
  if not found then raise exception 'INVALID_DELIVERY_ORDER' using errcode = 'P0001'; end if;
  insert into public.instagram_order_status_history (order_id, old_status, new_status, actor_id)
  values (p_order_id, order_row.status, order_row.status, p_actor_id);
  return to_jsonb(order_row);
end;
$$;

create or replace function public.create_instagram_shipping_batch(
  p_order_ids uuid[],
  p_partner_name text,
  p_note text,
  p_actor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  batch_row public.instagram_shipping_batches%rowtype;
  selected_order_count integer;
  selected_piece_count integer;
begin
  if coalesce(cardinality(p_order_ids), 0) not between 1 and 500
    or char_length(btrim(coalesce(p_partner_name, ''))) not between 2 and 120 then
    raise exception 'INVALID_SHIPPING_BATCH' using errcode = 'P0001';
  end if;

  -- قفل الطلبات بترتيب ثابت ومنع إدخال طلب توصيل أو طلب سبق تسليمه ضمن دفعة أخرى.
  perform 1 from public.instagram_orders
  where id = any(p_order_ids)
  order by id
  for update;

  select count(*), coalesce(sum(item_totals.pieces), 0)::integer
  into selected_order_count, selected_piece_count
  from public.instagram_orders orders
  join lateral (
    select coalesce(sum(quantity), 0)::integer as pieces
    from public.instagram_order_items
    where order_id = orders.id
  ) item_totals on true
  where orders.id = any(p_order_ids)
    and orders.order_type = 'شحن'
    and orders.status in ('قيد المتابعة', 'مؤجل')
    and orders.shipping_batch_id is null;

  if selected_order_count <> cardinality(p_order_ids) or selected_piece_count < 1 then
    raise exception 'INVALID_OR_ALREADY_BATCHED_SHIPPING_ORDER' using errcode = 'P0001';
  end if;

  insert into public.instagram_shipping_batches (
    partner_name, note, order_count, piece_count, created_by
  ) values (
    btrim(p_partner_name), btrim(coalesce(p_note, '')), selected_order_count, selected_piece_count, p_actor_id
  ) returning * into batch_row;

  update public.instagram_orders
  set shipping_batch_id = batch_row.id,
      shipping_partner = batch_row.partner_name,
      shipping_handed_at = now(),
      updated_at = now()
  where id = any(p_order_ids);

  return to_jsonb(batch_row);
end;
$$;

create or replace view public.instagram_inventory_stats
with (security_invoker = true)
as
select
  i.id as inventory_id,
  p.id as product_id,
  p.company_id,
  coalesce(company.name, '') as company_name,
  p.name as product_name,
  p.is_active as product_active,
  i.is_active as inventory_active,
  i.color,
  i.size,
  i.initial_quantity,
  coalesce(sum(oi.quantity) filter (where o.status = 'تم'), 0)::bigint as sold_quantity,
  coalesce(sum(oi.quantity) filter (where o.status = 'قيد المتابعة'), 0)::bigint as reserved_quantity,
  coalesce(sum(oi.quantity) filter (where o.status = 'مؤجل'), 0)::bigint as postponed_quantity,
  coalesce(sum(oi.quantity) filter (where o.status = 'ملغي'), 0)::bigint as cancelled_quantity,
  coalesce(sum(oi.quantity) filter (where o.status = 'مرتجع'), 0)::bigint as returned_quantity,
  i.available_quantity as remaining_quantity
from public.instagram_inventory i
join public.instagram_products p on p.id = i.product_id
left join public.users company on company.id::text = p.company_id and company.role = 'company'
left join public.instagram_order_items oi on oi.inventory_id = i.id
left join public.instagram_orders o on o.id = oi.order_id
group by i.id, p.id, p.company_id, company.name, p.name, p.is_active, i.is_active,
         i.color, i.size, i.initial_quantity, i.available_quantity;

